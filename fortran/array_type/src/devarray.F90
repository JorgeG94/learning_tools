   subroutine dp_1d_t_create(this, name, tag, ub, lb, fill)
      !! Allocate `data(lb(1):ub(1), ...)` on the host and register it under
      !! `tag`. `lb` defaults to 1; pass it by keyword. With `fill`, the
      !! array starts at that value, on the device too once mapped.
      class(dp_1d_t), intent(inout), target :: this
      character(len=*), intent(in) :: name
      type(mem_tag_t), intent(in) :: tag
      integer, intent(in) :: ub(1)
      integer, intent(in), optional :: lb(1)
      real(dp), intent(in), optional :: fill
      integer :: lo(1), ierr

      if (this%state /= ST_EMPTY) &
         call mem_fatal("create: '"//name//"' already created (as '"// &
                        mem_object_name(this%id)//"'); destroy it first")
      lo = 1
      if (present(lb)) lo = lb
      if (any(ub < lo - 1)) call mem_fatal("create: '"//name//"' has ub < lb - 1")

      allocate (this%data(lo(1):ub(1)), stat=ierr)
      if (ierr /= 0) call mem_fatal("create: host allocation failed for '"//name//"'")
      this%n = size(this%data, kind=int64)
      this%addr = c_null_ptr
      if (this%n > 0) this%addr = c_loc(this%data)
      this%has_fill = present(fill)
      if (present(fill)) then
         this%fill_value = fill
         this%data = fill
      end if

      this%id = mem_track(name, tag, this%bytes(), kind_code=MEM_KIND_R64, addr=this%addr, &
                          nelem=this%n, owner=dp_1d_t_owner(this), validate=dp_1d_t_validate)
      this%state = ST_HOST
   end subroutine dp_1d_t_create

