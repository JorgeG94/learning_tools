   subroutine dp_2d_t_check_intact(this, where)
      class(dp_2d_t), intent(in), target :: this
      character(len=*), intent(in) :: where
      if (this%state == ST_EMPTY) return
      if (.not. dp_2d_t_intact(this)) &
         call mem_fatal(where//": '"//mem_object_name(this%id)//"' was reallocated or deallocated"// &
                        " behind devarray (realloc-on-assignment? write x%data(:, :) = ..."// &
                        " instead of x%data = ...)")
   end subroutine dp_2d_t_check_intact

   logical function dp_2d_t_intact(x) result(ok)
      type(dp_2d_t), intent(in), target :: x
      ok = allocated(x%data)
      if (ok) ok = size(x%data, kind=int64) == x%n
      if (ok .and. x%n > 0) ok = c_associated(c_loc(x%data), x%addr)
   end function dp_2d_t_intact

