   subroutine dp_1d_t_assert_bounds(this, ub, lb)
      !! Fatal unless `data` has exactly these bounds (`lb` defaults to 1).
      !! Call once at init with the bounds your kernels declare: an
      !! explicit-shape dummy silently reinterprets mismatched bounds.
      class(dp_1d_t), intent(in), target :: this
      integer, intent(in) :: ub(1)
      integer, intent(in), optional :: lb(1)
      integer :: lo(1)
      call this%check_intact("assert_bounds")
      if (this%state == ST_EMPTY) call mem_fatal("assert_bounds: array not created")
      lo = 1
      if (present(lb)) lo = lb
      if (any(lbound(this%data) /= lo) .or. any(ubound(this%data) /= ub)) &
         call mem_fatal("assert_bounds: '"//mem_object_name(this%id)//"' has bounds "// &
                        bounds_str(lbound(this%data), ubound(this%data))//", expected "// &
                        bounds_str(lo, ub))
   end subroutine dp_1d_t_assert_bounds

   subroutine dp_1d_t_destroy(this)
      !! Unmap, deallocate and retire from the ledger. A no-op on an array
      !! that was never created, so teardown can call it unconditionally.
      class(dp_1d_t), intent(inout), target :: this

      if (this%state == ST_EMPTY) return
      if (.not. mem_is_live(this%id)) &
         call mem_fatal("destroy: '"//mem_object_name(this%id)//"' is already dead in the ledger."// &
                        " Was this object copied with intrinsic assignment?")
      call this%check_intact("destroy")
      if (this%state == ST_HOST_DEVICE) then
#if defined(DEVARRAY_ACC)
         !$acc exit data delete(this%data)
#elif defined(DEVARRAY_OMP)
         !$omp target exit data map(delete: this%data)
#endif
#ifdef DEVARRAY_DEVICE
         call mem_untrack_device(this%id)
#endif
      end if
      call mem_untrack(this%id)
      deallocate (this%data)
      this%id = 0
      this%state = ST_EMPTY
      this%addr = c_null_ptr
      this%n = 0
      this%has_fill = .false.
   end subroutine dp_1d_t_destroy

