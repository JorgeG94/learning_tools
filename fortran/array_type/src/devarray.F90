   subroutine i32_3d_t_create(this, name, tag, ub, lb, fill)
      !! Allocate `data(lb(1):ub(1), ...)` on the host and register it under
      !! `tag`. `lb` defaults to 1; pass it by keyword. With `fill`, the
      !! array starts at that value, on the device too once mapped.
      class(i32_3d_t), intent(inout), target :: this
      character(len=*), intent(in) :: name
      type(mem_tag_t), intent(in) :: tag
      integer, intent(in) :: ub(3)
      integer, intent(in), optional :: lb(3)
      integer(int32), intent(in), optional :: fill
      integer :: lo(3), ierr

      if (this%state /= ST_EMPTY) &
         call mem_fatal("create: '"//name//"' already created (as '"// &
                        mem_object_name(this%id)//"'); destroy it first")
      lo = 1
      if (present(lb)) lo = lb
      if (any(ub < lo - 1)) call mem_fatal("create: '"//name//"' has ub < lb - 1")

      allocate (this%data(lo(1):ub(1), lo(2):ub(2), lo(3):ub(3)), stat=ierr)
      if (ierr /= 0) call mem_fatal("create: host allocation failed for '"//name//"'")
      this%n = size(this%data, kind=int64)
      this%addr = c_null_ptr
      if (this%n > 0) this%addr = c_loc(this%data)
      this%has_fill = present(fill)
      if (present(fill)) then
         this%fill_value = fill
         this%data = fill
      end if

      this%id = mem_track(name, tag, this%bytes(), kind_code=MEM_KIND_I32, addr=this%addr, &
                          nelem=this%n, owner=i32_3d_t_owner(this), validate=i32_3d_t_validate)
      this%state = ST_HOST
   end subroutine i32_3d_t_create

   subroutine i32_3d_t_create_like_obj(this, name, tag, mold, fill)
      !! Create with the same bounds as another i32_3d_t.
      class(i32_3d_t), intent(inout), target :: this
      character(len=*), intent(in) :: name
      type(mem_tag_t), intent(in) :: tag
      class(i32_3d_t), intent(in), target :: mold
      integer(int32), intent(in), optional :: fill
      if (mold%state == ST_EMPTY) call mem_fatal("create_like: mold for '"//name//"' is not created")
      call mold%check_intact("create_like")
      call this%create(name, tag, ubound(mold%data), lbound(mold%data), fill)
   end subroutine i32_3d_t_create_like_obj

   subroutine i32_3d_t_create_like_arr(this, name, tag, mold, fill)
      !! Create with the same bounds as an allocatable array (bounds of an
      !! allocatable dummy are preserved, unlike an assumed-shape one).
      class(i32_3d_t), intent(inout), target :: this
      character(len=*), intent(in) :: name
      type(mem_tag_t), intent(in) :: tag
      integer(int32), allocatable, intent(in) :: mold(:, :, :)
      integer(int32), intent(in), optional :: fill
      if (.not. allocated(mold)) call mem_fatal("create_like: mold for '"//name//"' is not allocated")
      call this%create(name, tag, ubound(mold), lbound(mold), fill)
   end subroutine i32_3d_t_create_like_arr

   subroutine i32_3d_t_create_from(this, name, tag, source)
      !! Create with the bounds and the values of an allocatable array.
      class(i32_3d_t), intent(inout), target :: this
      character(len=*), intent(in) :: name
      type(mem_tag_t), intent(in) :: tag
      integer(int32), allocatable, intent(in) :: source(:, :, :)
