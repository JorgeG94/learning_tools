   subroutine dp_1d_t_check_intact(this, where)
      class(dp_1d_t), intent(in), target :: this
      character(len=*), intent(in) :: where
      if (this%state == ST_EMPTY) return
      if (.not. dp_1d_t_intact(this)) &
         call mem_fatal(where//": '"//mem_object_name(this%id)//"' was reallocated or deallocated"// &
                        " behind devarray (realloc-on-assignment? write x%data(:) = ..."// &
                        " instead of x%data = ...)")
   end subroutine dp_1d_t_check_intact

   logical function dp_1d_t_intact(x) result(ok)
      type(dp_1d_t), intent(in), target :: x
      ok = allocated(x%data)
      if (ok) ok = size(x%data, kind=int64) == x%n
      if (ok .and. x%n > 0) ok = c_associated(c_loc(x%data), x%addr)
   end function dp_1d_t_intact

   function dp_1d_t_owner(x) result(p)
      !! Address of the object itself, for the ledger's validator.
      type(dp_1d_t), intent(in), target :: x
      type(c_ptr) :: p
      p = c_loc(x)
   end function dp_1d_t_owner

   logical function dp_1d_t_validate(owner)
      !! Ledger callback: is the object at `owner` still as registered?
      type(c_ptr), value :: owner
      type(dp_1d_t), pointer :: p
      call c_f_pointer(owner, p)
      dp_1d_t_validate = dp_1d_t_intact(p)
   end function dp_1d_t_validate

