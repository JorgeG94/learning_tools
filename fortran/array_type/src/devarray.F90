   subroutine i32_fill_kernel(a, n, v, on_dev)
      integer(int64), intent(in) :: n
      integer(int32), intent(inout) :: a(n)
      integer(int32), intent(in) :: v
      logical, intent(in) :: on_dev
      integer(int64) :: i
#ifndef DEVARRAY_DEVICE
      if (on_dev) continue    ! without a device backend there is only the host copy
#endif
#if defined(DEVARRAY_ACC)
      !$acc parallel loop present(a) if(on_dev)
#elif defined(DEVARRAY_OMP)
      !$omp target teams distribute parallel do if(target: on_dev)
#endif
      do i = 1, n
         a(i) = v
      end do
   end subroutine i32_fill_kernel

   function bounds_str(lo, hi) result(s)
      integer, intent(in) :: lo(:), hi(:)
      character(len=:), allocatable :: s
      character(len=32) :: b
      integer :: i
      s = '('
      do i = 1, size(lo)
         write (b, '(i0, ":", i0)') lo(i), hi(i)
         s = s//trim(b)
         if (i < size(lo)) s = s//', '
      end do
      s = s//')'
   end function bounds_str

